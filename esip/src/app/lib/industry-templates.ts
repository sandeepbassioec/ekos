export function getIndustryTemplate(industryId: string): IndustryTemplate | undefined {
  return INDUSTRY_TEMPLATES.find((t) => t.id === industryId);
}

export function getProcessTemplate(processId: string): ProcessTemplate | undefined {
  return PROCESS_TEMPLATES[processId];
}

export function getProcessesByIndustry(industry: string): ProcessTemplate[] {
  return Object.values(PROCESS_TEMPLATES).filter((p) => p.category === industry);
}
