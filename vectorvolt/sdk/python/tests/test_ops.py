class OpsGolden(unittest.TestCase):
    def test_every_wrapped_opcode(self):
        def handler(op, rid, body):
            _m, _a, _req, ro, rp, _exp = CASES[rid - 1]
            return wire.encode_frame(rid, ro, bytes.fromhex(rp))

        srv = RawServer(handler)
        self.addCleanup(srv.close)
        c = VectorVoltClient("127.0.0.1", srv.port, timeout=5)
        c.connect()
        self.addCleanup(c.disconnect)
        for i, (method, args, req, _ro, _rp, exp) in enumerate(CASES):
            with self.subTest(method=method, case=i + 1):
                got = getattr(c, method)(*args)
                self.assertEqual(got, exp)
                self.assertEqual(srv.frames[i].hex(), req)
        self.assertEqual(len(srv.frames), len(CASES))

    def test_not_found_reply_to_non_optional_op_is_protocol_error(self):
        srv = RawServer(lambda op, rid, body: wire.encode_frame(rid, wire.NOT_FOUND))
        self.addCleanup(srv.close)
        c = VectorVoltClient("127.0.0.1", srv.port, timeout=5)
        c.connect()
        with self.assertRaises(wire.ProtocolError):
            c.upsert(1, [2])
        self.assertIsNone(c._sock)


