async function mock(reply: (id: bigint) => Buffer): Promise<{ port: number; reqs: Buffer[]; close: () => void }> {
  const reqs: Buffer[] = [];
  const server = net.createServer((sock) => {
    let buf = Buffer.alloc(0);
    sock.on("data", (d) => {
      buf = Buffer.concat([buf, d]);
      for (;;) {
        if (buf.length < HEADER_SIZE) return;
        const h = decodeHeader(buf);
        if (buf.length < HEADER_SIZE + h.payloadLen) return;
        reqs.push(Buffer.from(buf.subarray(0, HEADER_SIZE + h.payloadLen)));
        buf = buf.subarray(HEADER_SIZE + h.payloadLen);
        sock.write(reply(h.requestId));
      }
    });
    sock.on("error", () => {});
  });
  await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
  const port = (server.address() as net.AddressInfo).port;
  return { port, reqs, close: () => server.close() };
}

test("ops: every wrapped opcode encodes the golden request and decodes the reply", async () => {
  const m = await mock((id) => {
    const [, , , respOp, resp] = CASES[Number(id) - 1];
    return encodeFrame(id, respOp, Buffer.from(resp, "hex"));
  });
  const c = new VectorVoltClient("127.0.0.1", m.port);
  await c.connect();
  try {
    for (let i = 0; i < CASES.length; i++) {
      const [method, args, req, , , want] = CASES[i];
      const got = await (c as unknown as Record<string, (...a: unknown[]) => Promise<unknown>>)[method](...args);
      assert.deepEqual(got, want, `${method} (case ${i + 1}) result`);
      assert.equal(m.reqs[i].toString("hex"), req, `${method} (case ${i + 1}) request frame`);
    }
    assert.equal(m.reqs.length, CASES.length);
  } finally {
    await c.disconnect();
    m.close();
  }
});

test("ops: NotFound reply to a non-optional op is a protocol error and drops the connection", async () => {
  const m = await mock((id) => encodeFrame(id, Op.NotFound));
  const c = new VectorVoltClient("127.0.0.1", m.port);
  await c.connect();
  await assert.rejects(c.upsert(1n, [2n]), ProtocolError);
  await assert.rejects(c.upsert(1n, [2n]), /Not connected/);
  m.close();
});
