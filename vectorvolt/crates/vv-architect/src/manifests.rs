//! Optional deploy manifest generation — `--terraform-out`/`--k8s-out` on a
//! sizing run. Per the plan: "Output: human report + vectorvolt.toml deploy
//! config + optional Terraform/K8s manifests".
//!
//! Honest scope: these are real, valid HCL/YAML generated directly from the
//! already-computed [`SizingPlan`] — not a second guess at sizing, just a
//! different serialization of the same numbers into a deployable shape. The
//! Terraform output targets AWS EC2 (the plan gives no target cloud, so a
//! concrete, useful default was chosen over an abstract/fake placeholder);
//! adapting the resource block to GCP/Azure is a mechanical follow-up, not a
//! new sizing decision.

use crate::rules::SizingPlan;

/// (min_vcpu, min_ram_gb, instance_type) — smallest-first, so the first
/// entry meeting both minimums is the cheapest adequate instance. A small,
/// deliberately incomplete set of common general-purpose EC2 types; extend
/// as needed.
const EC2_INSTANCE_TYPES: &[(u32, u32, &str)] = &[
    (2, 4, "t3.medium"),
    (2, 8, "t3.large"),
    (4, 16, "m5.xlarge"),
    (8, 32, "m5.2xlarge"),
    (16, 64, "m5.4xlarge"),
    (32, 128, "m5.8xlarge"),
    (64, 256, "m5.16xlarge"),
];

fn ec2_instance_type_for(cpu_cores: u32, ram_gb: u32) -> &'static str {
    EC2_INSTANCE_TYPES
        .iter()
        .find(|(min_cpu, min_ram, _)| cpu_cores <= *min_cpu && ram_gb <= *min_ram)
        .map(|(_, _, name)| *name)
        .unwrap_or_else(|| EC2_INSTANCE_TYPES.last().unwrap().2) // biggest we know of
}

/// Minimal, valid Terraform HCL provisioning `plan.node_count` EC2 instances
/// sized from the rule engine's output.
pub fn render_terraform(plan: &SizingPlan) -> String {
    let instance_type = ec2_instance_type_for(plan.cpu_cores_per_node, plan.ram_gb_per_node);
    format!(
        r#"# Generated by vv-architect — VectorVolt cluster sizing.
# {node_count} node(s), {cpu} vCPU / {ram} GiB RAM each, {disk} GB {disk_type} disk each.

variable "node_count" {{
  description = "Number of VectorVolt cluster nodes"
  type        = number
  default     = {node_count}
}}

resource "aws_instance" "vectorvolt_node" {{
  count         = var.node_count
  ami           = "ami-0000000000000000" # placeholder — set to your VectorVolt AMI
  instance_type = "{instance_type}"

  root_block_device {{
    volume_size = {disk}
    volume_type = "gp3"
  }}

  tags = {{
    Name = "vectorvolt-node-${{count.index}}"
  }}
}}
"#,
        node_count = plan.node_count,
        cpu = plan.cpu_cores_per_node,
        ram = plan.ram_gb_per_node,
        disk = plan.disk_gb_per_node,
        disk_type = plan.disk_type,
        instance_type = instance_type,
    )
}

/// Minimal, valid Kubernetes StatefulSet + headless Service manifest, sized
/// from the rule engine's output. CPU/memory requests and limits are set
/// equal (guaranteed QoS) since this is a stateful, latency-sensitive OLTP
/// workload, not a bursty one.
pub fn render_k8s(plan: &SizingPlan) -> String {
    format!(
        r#"apiVersion: v1
kind: Service
metadata:
  name: vectorvolt
  labels:
    app: vectorvolt
spec:
  clusterIP: None
  selector:
    app: vectorvolt
  ports:
    - port: 5995
      name: wire
---
apiVersion: apps/v1
kind: StatefulSet
metadata:
  name: vectorvolt
spec:
  serviceName: vectorvolt
  replicas: {node_count}
  selector:
    matchLabels:
      app: vectorvolt
  template:
    metadata:
      labels:
        app: vectorvolt
    spec:
      containers:
        - name: vectorvolt
          image: vectorvolt:latest
          ports:
            - containerPort: 5995
              name: wire
          resources:
            requests:
              cpu: "{cpu}"
              memory: "{ram}Gi"
            limits:
              cpu: "{cpu}"
              memory: "{ram}Gi"
          volumeMounts:
            - name: data
              mountPath: /var/lib/vectorvolt
  volumeClaimTemplates:
    - metadata:
        name: data
      spec:
        accessModes: ["ReadWriteOnce"]
        resources:
          requests:
            storage: {disk}Gi
"#,
        node_count = plan.node_count,
        cpu = plan.cpu_cores_per_node,
        ram = plan.ram_gb_per_node,
        disk = plan.disk_gb_per_node,
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::rules::{SizingInputs, compute};

    fn example_plan() -> SizingPlan {
        compute(
            SizingInputs {
                estimated_tps: 50_000,
                estimated_data_gb: 400.0,
                replication_factor: 2,
            },
            Some("order_id".to_owned()),
        )
    }

    #[test]
    fn ec2_instance_lookup_picks_smallest_adequate_type() {
        assert_eq!(ec2_instance_type_for(2, 4), "t3.medium");
        assert_eq!(ec2_instance_type_for(2, 8), "t3.large");
        assert_eq!(ec2_instance_type_for(4, 16), "m5.xlarge");
    }

    #[test]
    fn ec2_instance_lookup_falls_back_to_largest_known_type_for_huge_workloads() {
        assert_eq!(ec2_instance_type_for(128, 512), "m5.16xlarge");
    }

    #[test]
    fn terraform_output_contains_correct_node_count_and_disk_size() {
        let plan = example_plan();
        let hcl = render_terraform(&plan);
        assert!(hcl.contains(&format!("default     = {}", plan.node_count)));
        assert!(hcl.contains(&format!("volume_size = {}", plan.disk_gb_per_node)));
        assert!(hcl.contains("resource \"aws_instance\" \"vectorvolt_node\""));
    }

    #[test]
    fn k8s_output_is_valid_yaml_with_correct_replica_count() {
        let plan = example_plan();
        let yaml = render_k8s(&plan);
        // Two YAML documents separated by `---` — validate each parses.
        let docs: Vec<&str> = yaml.split("---").collect();
        assert_eq!(docs.len(), 2);
        for doc in &docs {
            let _: serde_yaml::Value =
                serde_yaml::from_str(doc).expect("generated manifest must be valid YAML");
        }
        let statefulset: serde_yaml::Value = serde_yaml::from_str(docs[1]).unwrap();
        assert_eq!(
            statefulset["spec"]["replicas"].as_u64(),
            Some(plan.node_count as u64)
        );
    }

    #[test]
    fn k8s_output_cpu_memory_requests_match_sizing_plan() {
        let plan = example_plan();
        let yaml = render_k8s(&plan);
        assert!(yaml.contains(&format!("cpu: \"{}\"", plan.cpu_cores_per_node)));
        assert!(yaml.contains(&format!("memory: \"{}Gi\"", plan.ram_gb_per_node)));
    }

    #[test]
    fn k8s_storage_request_matches_disk_sizing() {
        let plan = example_plan();
        let yaml = render_k8s(&plan);
        assert!(yaml.contains(&format!("storage: {}Gi", plan.disk_gb_per_node)));
    }
}
