pub fn powershell_completion() -> String {
    r#"# PowerShell completion for vvctl
Register-ArgumentCompleter -Native -CommandName vvctl -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    $commands = @(
        'serve', 'catalog', 'config', 'connect', 'table', 'bench', 'hal',
        'store', 'wal', 'http', 'keygen', 'tune', 'profile', 'topology',
        'completion', 'server', 'support-bundle', 'config-audit', 'ping',
        'status', 'bench-net', 'disconnect', 'install', 'uninstall',
        'cluster-topology', 'control', 'version'
    )
    $commands | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}
"#.to_string()
}

pub fn generate_completion(shell: &CompletionShell) -> String {
    match shell {
        CompletionShell::Bash => bash_completion(),
        CompletionShell::Zsh => zsh_completion(),
        CompletionShell::Fish => fish_completion(),
        CompletionShell::Powershell => powershell_completion(),
    }
}

pub fn run(args: CompletionArgs) -> Result<()> {
    print!("{}", generate_completion(&args.shell));
    Ok(())
}
