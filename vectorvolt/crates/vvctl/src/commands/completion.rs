//! `vvctl completion` — print shell completion scripts (VV-CTL-181).

use anyhow::Result;
use clap::Args;

#[derive(Clone, Debug, clap::ValueEnum)]
pub enum CompletionShell {
    Bash,
    Zsh,
    Fish,
    Powershell,
}

#[derive(Args)]
pub struct CompletionArgs {
    /// Target shell.
    pub shell: CompletionShell,
}

pub fn bash_completion() -> String {
    r#"# bash completion for vvctl
_vvctl() {
    local cur prev words cword
    _init_completion || return
    local commands="serve catalog config connect table bench hal store wal http keygen tune profile topology completion server support-bundle config-audit ping status bench-net disconnect install uninstall cluster-topology control version"
    case "$prev" in
        table)
            COMPREPLY=($(compgen -W "insert get delete scan stats" -- "$cur"))
            return ;;
        config)
            COMPREPLY=($(compgen -W "init show validate" -- "$cur"))
            return ;;
        completion)
            COMPREPLY=($(compgen -W "bash zsh fish powershell" -- "$cur"))
            return ;;
    esac
    if [[ "$cur" == -* ]]; then
        COMPREPLY=($(compgen -W "--verbose --output --no-color --quiet --help --version" -- "$cur"))
        return
    fi
    COMPREPLY=($(compgen -W "$commands" -- "$cur"))
}
complete -F _vvctl vvctl
"#.to_string()
}

pub fn zsh_completion() -> String {
    r#"#compdef vvctl
_vvctl() {
    local -a commands
    commands=(
        'serve:Start a VectorVolt table server'
        'catalog:ShardCatalog management'
        'config:Master configuration management'
        'connect:Send a single command to a running server'
        'table:Table read/write commands'
        'bench:In-process micro-benchmark'
        'hal:Report CPU features'
        'store:KV store commands'
        'wal:WAL inspection'
        'http:HTTP gateway commands'
        'keygen:Generate a secret key'
        'tune:Detect hardware and derive config'
        'profile:Emit the host SystemProfile'
        'topology:Show CPU/NUMA topology'
        'completion:Print shell completion scripts'
        'server:Server management commands'
        'support-bundle:Collect diagnostics'
        'config-audit:Audit a config file'
        'ping:Send pings to a server'
        'status:Query server status'
        'bench-net:Benchmark network throughput'
        'disconnect:Disconnect from a server'
        'install:Post-install setup'
        'uninstall:Remove VectorVolt configuration'
        'cluster-topology:Show cluster node/shard distribution'
        'control:Control plane subcommands'
        'version:Print version and build info'
    )
    _describe 'vvctl commands' commands
    _arguments \
        '(-v --verbose)'{-v,--verbose}'[Enable verbose output]' \
        '--output[Output format]:format:(text json)' \
        '--no-color[Disable ANSI color codes]' \
        '(-q --quiet)'{-q,--quiet}'[Suppress decorative output]' \
        '*::arg:->args'
    case $state in
        args)
            case $words[1] in
                serve)
                    _arguments '--dir[Data directory]:dir:_files' '--addr[Bind address]:addr:' ;;
                table)
                    local -a subcmds
                    subcmds=('insert:Insert a row' 'get:Get a row' 'delete:Delete a row' 'scan:Scan rows' 'stats:Table stats')
                    _describe 'table subcommands' subcmds ;;
            esac ;;
    esac
}
_vvctl "$@"
"#.to_string()
}

