//! `vvctl tune` — hardware auto-configuration (VV-CFG-006).
//!
//! Detects the host's CPU topology, SIMD tier, and fsync latency, then
//! derives recommended engine configuration values and emits an annotated
//! TOML file that can be passed directly to `vvctl serve --config <path>`.
//!
//! ## Sub-commands (via flags)
//!
//! | Flag | Behaviour |
//! |---|---|
//! | *(none)* | Detect + print derived config summary |
//! | `--explain` | Include per-field rationale in the TOML output |
//! | `--diff` | Show drift between derived values and an existing config file |
//! | `--apply` | Write the TOML to the given `--output-file` (consent-gated) |
//!
//! ## Derivation rules
//!
//! * **flush_threshold** — number of rows that triggers a buffer flush. Derived
//!   from the outermost shared cache (L3 > L2 > L1d), assuming each row is
//!   `row_bytes` wide (defaults to 64 B, one cache line). Clamped to [1 024,
//!   1 048 576].
//!
//! * **durability** — `"fsync"` when a measured fsync roundtrip is below 5 ms;
//!   `"buffered"` otherwise (e.g. a network storage device where fsync is
//!   expensive).
//!
//! * **max_partitions** — writer count × 8, clamped to [4, 256].

use crate::ui;
use anyhow::{Context, Result};
use clap::Args;
use std::fmt::Write as FmtWrite;
use std::io::Write as IoWrite;
use std::path::PathBuf;
use vectorvolt_hal::{CycleTimer, Stopwatch};

// ── Args ──────────────────────────────────────────────────────────────────────

#[derive(Args)]
pub struct TuneArgs {
    /// Include per-field rationale in the TOML output.
    #[arg(long)]
    pub explain: bool,

    /// Show drift between the derived config and an existing TOML file.
    #[arg(long)]
    pub diff: Option<PathBuf>,

    /// Write the derived TOML to this file (requires confirmation unless
    /// `--force` is also passed).
    #[arg(long)]
    pub apply: Option<PathBuf>,

    /// Skip the interactive confirmation prompt when `--apply` is set.
    #[arg(long)]
    pub force: bool,

    /// Assumed bytes per row for cache-capacity calculations.
    #[arg(long, default_value = "64")]
    pub row_bytes: usize,
}

// ── Derived config ────────────────────────────────────────────────────────────

/// Engine configuration values derived from hardware probing.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DerivedConfig {
    /// Number of rows that triggers a buffer flush.
    pub flush_threshold: usize,
    /// `"fsync"` | `"buffered"`.
    pub durability: &'static str,
    /// Maximum number of in-memory micro-partitions.
    pub max_partitions: usize,
    /// Measured fsync roundtrip in nanoseconds.
    pub fsync_ns: u64,
    /// Number of recommended writer cores.
    pub writer_count: usize,
    /// One-line topology summary (for display and explain output).
    pub topo_summary: String,
}

impl DerivedConfig {
    /// Derive a config by probing the running hardware.
    pub fn probe(row_bytes: usize) -> Self {
        let topo = vectorvolt_hal::CpuTopology::detect();
        let roles = vectorvolt_hal::CoreRoleMap::derive(&topo);
        let writer_count = roles.writers.len().max(1);

        // flush_threshold: fit as many rows as possible in the outermost cache
        // so a flush batch is L3-resident during column encoding.
        let cache_bytes = topo
            .cache
            .l3_bytes
            .or(topo.cache.l2_bytes)
            .or(topo.cache.l1d_bytes)
            .unwrap_or(16 * 1024 * 1024);
        let effective_row_bytes = row_bytes.max(1);
        let flush_threshold = (cache_bytes / effective_row_bytes).clamp(1_024, 1_048_576);

        // durability: calibrate a single fsync() against a temp file.
        let fsync_ns = measure_fsync_ns();
        let durability = if fsync_ns < 5_000_000 {
            "fsync"
        } else {
            "buffered"
        };

        // max_partitions: generous multiple of the writer count.
        let max_partitions = (writer_count * 8).clamp(4, 256);

        DerivedConfig {
            flush_threshold,
            durability,
            max_partitions,
            fsync_ns,
            writer_count,
            topo_summary: topo.summary(),
        }
    }

    /// Emit the derived values as a TOML string.
    ///
    /// When `explain` is true each field is preceded by comment lines that
    /// explain the rationale behind the derived value.
    pub fn to_annotated_toml(&self, explain: bool) -> String {
        let mut out = String::new();

        if explain {
            let _ = writeln!(
                out,
                "# Generated by `vvctl tune` — edit values then pass to `vvctl serve --config`."
            );
            let _ = writeln!(out, "#");
            let _ = writeln!(out, "# Hardware: {}", self.topo_summary);
            let _ = writeln!(out, "# Measured fsync latency: {}", fmt_ns(self.fsync_ns));
            let _ = writeln!(out, "# Recommended writer cores: {}", self.writer_count);
            let _ = writeln!(out);
        }

        if explain {
            let _ = writeln!(
                out,
                "# flush_threshold: rows buffered before a flush is triggered."
            );
            let _ = writeln!(
                out,
                "#   Derived from the outermost shared cache so a flush batch is L3-resident"
            );
            let _ = writeln!(
                out,
                "#   during column encoding. Increase for higher throughput at the cost of"
            );
            let _ = writeln!(out, "#   larger write latency spikes.");
        }
        let _ = writeln!(out, "flush_threshold = {}", self.flush_threshold);

        if explain {
            let _ = writeln!(out);
            let _ = writeln!(
                out,
                "# durability: how writes are persisted before acknowledging to the client."
            );
            let _ = writeln!(
                out,
                "#   \"fsync\"    — O_SYNC + fsync() after every batch flush."
            );
            let _ = writeln!(
                out,
                "#   \"buffered\" — kernel page cache flush (lower latency, less durable)."
            );
            let _ = writeln!(
                out,
                "#   Derived from measured fsync latency: {}.",
                fmt_ns(self.fsync_ns)
            );
            let _ = writeln!(
                out,
                "#   Switch to \"buffered\" if your storage device is slow (NFS, HDD, etc.)."
            );
        }
        let _ = writeln!(out, "durability = \"{}\"", self.durability);

        if explain {
            let _ = writeln!(out);
            let _ = writeln!(
                out,
                "# max_partitions: maximum in-memory micro-partitions before compaction."
            );
            let _ = writeln!(
                out,
                "#   Set to writer_count × 8 (writer_count = {}).",
                self.writer_count
            );
        }
        let _ = writeln!(out, "max_partitions = {}", self.max_partitions);

        out
    }

    /// Diff self against an already-parsed config's raw field values.
    ///
    /// Returns a list of `(field, current_value, derived_value)` tuples for
    /// every field whose derived value differs from the file's value.
    pub fn diff_toml(&self, toml_text: &str) -> Vec<(&'static str, String, String)> {
        use vectorvolt_engine::config::EngineConfig;
        let parsed = match EngineConfig::from_toml(toml_text) {
            Ok(c) => c,
            Err(_) => return vec![("(parse error)", String::new(), String::new())],
        };
        let mut diffs = Vec::new();
        if let Some(ft) = parsed.flush_threshold
            && ft != self.flush_threshold
        {
            diffs.push((
                "flush_threshold",
                ft.to_string(),
                self.flush_threshold.to_string(),
            ));
        }
        if let Some(ref d) = parsed.durability
            && d.as_str() != self.durability
        {
            diffs.push(("durability", d.clone(), self.durability.to_string()));
        }
        if let Some(mp) = parsed.max_partitions
            && mp != self.max_partitions
        {
            diffs.push((
                "max_partitions",
                mp.to_string(),
                self.max_partitions.to_string(),
            ));
        }
        diffs
    }
}

// ── fsync calibration ─────────────────────────────────────────────────────────

/// Write 4 KB to a temp file, call `sync_all()`, and return the roundtrip
/// in nanoseconds.  Returns 0 on any error (treated as very fast = fsync).
pub fn measure_fsync_ns() -> u64 {
    let timer = CycleTimer::calibrate();
    let dir = std::env::temp_dir();
    let path = dir.join(format!("vvctl_tune_{}.tmp", std::process::id()));

    let result = (|| -> std::io::Result<u64> {
        let mut f = std::fs::File::create(&path)?;
        f.write_all(&[0u8; 4096])?;
        let sw = Stopwatch::start();
        f.sync_all()?;
        Ok(sw.elapsed_ns(&timer))
    })();

    let _ = std::fs::remove_file(&path);
    result.unwrap_or(0)
}

// ── run ───────────────────────────────────────────────────────────────────────

pub fn run(args: TuneArgs) -> Result<()> {
    let row_bytes = if args.row_bytes == 0 {
        64
    } else {
        args.row_bytes
    };
    let cfg = DerivedConfig::probe(row_bytes);

    ui::section_header("VectorVolt tune — derived engine configuration");

    // Always print the summary table.
    {
        let mut t = ui::styled_table();
        t.set_header(["Setting", "Derived value", "Source"]);
        t.add_row([
            "flush_threshold",
            &cfg.flush_threshold.to_string(),
            "outermost cache / row_bytes",
        ]);
        t.add_row([
            "durability",
            cfg.durability,
            if cfg.fsync_ns < 5_000_000 {
                "fsync < 5 ms"
            } else {
                "fsync ≥ 5 ms → buffered"
            },
        ]);
        t.add_row([
            "max_partitions",
            &cfg.max_partitions.to_string(),
            "writer_count × 8",
        ]);
        t.add_row([
            "fsync latency (measured)",
            &fmt_ns(cfg.fsync_ns),
            "temp-file calibration",
        ]);
        println!("{t}");
    }

    // --diff: compare against an existing file.
    if let Some(ref path) = args.diff {
        let text = std::fs::read_to_string(path)
            .with_context(|| format!("read config {}", path.display()))?;
        let diffs = cfg.diff_toml(&text);
        if diffs.is_empty() {
            ui::print_ok("no drift — derived values match the existing config");
        } else {
            ui::print_warn(&format!("{} field(s) differ:", diffs.len()));
            for (field, current, derived) in &diffs {
                println!("  {field}: file={current}  derived={derived}");
            }
        }
    }

    // Print the annotated TOML (always, unless --quiet; explains only if --explain).
    if !ui::quiet_mode() {
        ui::section_header(if args.explain {
            "Annotated TOML (--explain)"
        } else {
            "TOML (pass this to `vvctl serve --config <file>`)"
        });
        print!("{}", cfg.to_annotated_toml(args.explain));
    }

    // --apply: write to disk.
    if let Some(ref path) = args.apply {
        if !args.force {
            println!("\nWrite derived config to {}? [y/N] ", path.display());
            let mut line = String::new();
            std::io::stdin().read_line(&mut line)?;
            if !line.trim().eq_ignore_ascii_case("y") {
                println!("Aborted.");
                return Ok(());
            }
        }
        let toml = cfg.to_annotated_toml(args.explain);
        std::fs::write(path, &toml).with_context(|| format!("write config {}", path.display()))?;
        ui::print_ok(&format!("wrote {}", path.display()));
    }

    Ok(())
}

// ── helpers ───────────────────────────────────────────────────────────────────

fn fmt_ns(ns: u64) -> String {
    if ns < 1_000 {
        format!("{ns} ns")
    } else if ns < 1_000_000 {
        format!("{:.1} µs", ns as f64 / 1_000.0)
    } else if ns < 1_000_000_000 {
        format!("{:.2} ms", ns as f64 / 1_000_000.0)
    } else {
        format!("{:.2} s", ns as f64 / 1_000_000_000.0)
    }
}
